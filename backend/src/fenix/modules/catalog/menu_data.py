from dataclasses import dataclass, field


@dataclass(frozen=True)
class SizeData:
    name: str
    price: int
    portion: str | None = None


@dataclass(frozen=True)
class GroupData:
    name: str
    min_choice: int
    max_choice: int
    options: tuple[tuple[str, int], ...]


@dataclass(frozen=True)
class DishData:
    name: str
    price: int | None = None
    description: str = ""
    portion: str | None = None
    sizes: tuple[SizeData, ...] = ()
    groups: tuple[GroupData, ...] = ()


@dataclass(frozen=True)
class CategoryData:
    name: str
    dishes: tuple[DishData, ...]
    description: str = ""
    groups: tuple[GroupData, ...] = field(default=())


